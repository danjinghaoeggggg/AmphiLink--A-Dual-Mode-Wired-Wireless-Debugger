#ifndef TRANSPORT_PATH_CONFIG_H
#define TRANSPORT_PATH_CONFIG_H

#include "sw3.h"

#define DAP_PATH_MODE_THREE_STATE       0
#define DAP_PATH_MODE_TWO_STATE         1
#define DAP_PATH_MODE_FORCE_WIRED       2
#define DAP_PATH_MODE_FORCE_WIRELESS    3
#define DAP_PATH_MODE_FORCE_AUTO        4

/* Select the board path policy at build time. */
#ifndef DAP_PATH_SELECTION_MODE
#define DAP_PATH_SELECTION_MODE DAP_PATH_MODE_TWO_STATE
#endif

#define DAP_PATH_SW3_WIRED    SW3_STATE_1
#define DAP_PATH_SW3_AUTO     SW3_STATE_2
#define DAP_PATH_SW3_WIRELESS SW3_STATE_3

#define DAP_PATH_AUTO_PREFER_WIRELESS 1

#if ((DAP_PATH_AUTO_PREFER_WIRELESS != 0) && \
     (DAP_PATH_AUTO_PREFER_WIRELESS != 1))
#error "DAP_PATH_AUTO_PREFER_WIRELESS must be 0 or 1"
#endif

#if (DAP_PATH_SELECTION_MODE < DAP_PATH_MODE_THREE_STATE) || \
    (DAP_PATH_SELECTION_MODE > DAP_PATH_MODE_FORCE_AUTO)
#error "DAP_PATH_SELECTION_MODE is invalid"
#endif

#endif
